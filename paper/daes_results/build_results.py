"""Audit archived experiments and rebuild the DAES tables and vector figures.

This analyses existing records; it does not run MATLAB, train models or use a board.
Run: python build_results.py --manuscript /path/to/DAES_Special_Issue
"""
from pathlib import Path
import argparse
import hashlib
import json

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "source"
POWER_EXCLUDED = {"E-BAT-01b", "E-BAT-01n"}
THD_EXCLUDED = {"E-DC-01c", "E-BAT-02c"}
VARIANTS = [
    ("MPCC-D", "MPCC_D", 20), ("D-FFT1", "MPCC_D_F1", 20),
    ("D-FFT10", "MPCC_D_F10", 20), ("D-RLS", "MPCC_D_R", 20),
    ("D-BLS", "MPCC_D_M1", 20), ("MPCC-H", "MPCC_H6", 20),
    ("MPCC-R", "MPCC_R6", 20), ("PR", "CRPR", 100),
    ("MPCC-P", "MPCC_P", 100),
]
ABLATIONS = [
    ("Complete MPCC-R", "MPCC_R"), ("Oracle, immediate", "MPCC_R_OR"),
    ("Oracle, 60 ms", "MPCC_R_OR3"), ("Without both safeguards", "MPCC_R_v5"),
    ("Without reference limit", "MPCC_R_noM11"),
    ("Without predictor correction", "MPCC_R_noM14"),
    ("Permanent 55 A cap on H", "MPCC_H_L55"),
    ("Residual detector, same policy", "MPCC_R_RES"),
]
COLORS = {"PR": "#777777", "D": "#e69526", "H": "#2563a6", "R": "#22805e"}
PDF_METADATA = {"CreationDate": None, "ModDate": None, "Creator": "DAES experimental results"}


def read(name):
    return pd.read_csv(SOURCE / name)


def table(path, caption, label, columns, headings, rows, note):
    body = "\n".join(" & ".join(map(str, row)) + r" \\" for row in rows)
    path.write_text(
        "% Generated by results_evidence/build_results.py.\n"
        r"\begin{table}[!tb]\centering" + "\n"
        + rf"\caption{{{caption}}}\label{{{label}}}" + "\n"
        + r"\begingroup\fontsize{8}{9.5}\selectfont\setlength{\tabcolsep}{3pt}" + "\n"
        + r"\renewcommand{\arraystretch}{1.12}" + "\n"
        + r"\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}" + columns + r"@{}}\toprule" + "\n"
        + " & ".join(headings) + r" \\\midrule" + "\n" + body + "\n"
        + r"\bottomrule\end{tabular*}" + "\n"
        + r"\par\smallskip\begin{minipage}{\linewidth}\fontsize{7.5}{9}\selectfont "
        + note + r"\end{minipage}\endgroup\end{table}" + "\n",
        encoding="utf-8",
    )


def calculate():
    manifest = json.loads((HERE / "source_manifest.json").read_text())
    for entry in manifest:
        payload = (HERE / entry["local"]).read_bytes()
        assert len(payload) == entry["bytes"], entry["local"]
        assert hashlib.sha256(payload).hexdigest() == entry["sha256"], entry["local"]
    membership = read("attack_membership.csv")
    cases = membership.loc[membership.cohort.eq("main13"), "case"].tolist()
    assert len(cases) == len(set(cases)) == 13
    assert set(membership.loc[~membership.power11 & membership.cohort.eq("main13"), "case"]) == POWER_EXCLUDED
    assert set(membership.loc[~membership.thd11 & membership.cohort.eq("main13"), "case"]) == THD_EXCLUDED
    matched = read("matched_case_metrics.csv")
    summaries = []
    for name, variant, rate in VARIANTS:
        q = matched[matched.source_variant.eq(variant)].set_index("test_id").loc[cases]
        assert len(q) == 13
        # Independently recover every comparison endpoint from individual scorecards.
        for case in cases:
            r = read(f"scorecards/{case}_{variant}.csv").iloc[0]
            assert r.test_id == case and r.VARIANT_NAME == variant and r.status == "OK"
            assert np.isclose(r.t_on, .7) and np.isclose(r.dwell, .3)
            for field, key in [("power_retention_pct", "power_retention_pct"),
                               ("dVdc_V", "bus_deviation_V"), ("trip", "latch_code"),
                               ("THD50_pre_pct", "THD50_pre_pct"), ("THD50_dur_pct", "THD50_dur_pct")]:
                assert np.isclose(r[field], q.loc[case, key], atol=1e-9, rtol=0), (case, variant, field)
        p = q.power_retention_pct - 100
        latch = q.latch_code.ne(0)
        joint = p.abs().le(1) & ~latch
        assert (joint.astype(int) == q.joint_success).all()
        common = q.loc[[c for c in cases if c not in THD_EXCLUDED]]
        assert common.THD_valid_own.eq(1).all()
        summaries.append(dict(controller=name, source_variant=variant, control_kHz=rate,
            thd_pre_pct=common.THD50_pre_pct.mean(), thd_attack_pct=common.THD50_dur_pct.mean(),
            power13_pp=p.abs().mean(), power11_pp=p.loc[[c for c in cases if c not in POWER_EXCLUDED]].abs().mean(),
            bus13_V=q.bus_deviation_V.abs().mean(), latches=int(latch.sum()), joint=int(joint.sum())))
    summaries = pd.DataFrame(summaries)
    aw = read("attack_window_metrics.csv")
    archive = json.loads((SOURCE / "archived_computed_values.json").read_text())
    ablations = []
    for name, variant in ABLATIONS:
        q = aw[aw.variant.eq(variant)].set_index("case").loc[cases]
        assert len(q) == 13 and q.index.is_unique
        assert ((q.power_err_pp.abs().le(1) & q.latched.eq(0)).astype(int) == q.joint).all()
        r = dict(configuration=name, variant=variant,
            power11_pp=q.loc[[c for c in cases if c not in POWER_EXCLUDED]].power_err_pp.abs().mean(),
            energy_kJ=q.energy_deficit_J.sum()/1000, latches=int(q.latched.sum()), joint=int(q.joint.sum()))
        old = next(a for a in archive["oracle"] if a["variant"] == variant)
        for key, oldkey in [("power11_pp", "power11_pp"), ("energy_kJ", "energy_kJ"), ("latches", "latched"), ("joint", "joint")]:
            assert np.isclose(r[key], old[oldkey], atol=1e-9, rtol=0)
        if variant in ("MPCC_H_L55", "MPCC_R_RES"):
            source_variant = "MPCC_H6_L55" if variant == "MPCC_H_L55" else "MPCC_R6_RES"
            for case in cases:
                raw = read(f"scorecards/{case}_{source_variant}.csv").iloc[0]
                assert np.isclose(raw.power_retention_pct-100, q.loc[case, "power_err_pp"], atol=1e-9, rtol=0)
                assert int(raw.trip != 0) == q.loc[case, "latched"]
        ablations.append(r)
    ablations = pd.DataFrame(ablations)
    ids = []
    for filename, cohort, expected in [("ids_benchmark.csv", "Benchmark", 104), ("ids_random.csv", "Random", 17)]:
        d = read(filename); attacked = d[d.attacked.eq(1)]; benign = d[d.attacked.eq(0)]
        assert len(attacked) == expected
        hits = attacked[attacked.any_hit.eq(1)]
        assert len(hits) == int(attacked.lat_ms.notna().sum())
        ids.append(dict(cohort=cohort, attacked=len(attacked), benign=len(benign),
            any_hit=int(attacked.any_hit.sum()), exact=int(attacked.exact.sum()),
            detected_by_40ms=int(attacked.lat_ms.le(40 + 1e-8).sum()),
            median_ms=hits.lat_ms.median(), max_ms=hits.lat_ms.max(),
            pre_flags=int(attacked.fa_pre.sum()), benign_flags=int(benign.fa_pre.sum()),
            post_flags=int(attacked.fa_post.sum())))
    ids = pd.DataFrame(ids)
    assert ids.any_hit.tolist() == [102, 17] and ids.exact.tolist() == [40, 5]
    eq = read("equivalence.csv"); full = eq[eq.stage.eq("full")]
    hil = read("hil_outcomes.csv").set_index("case")
    assert len(full) == len(hil) == 7
    for _, r in full.iterrows():
        for metric in ["power_retention_pct", "dVdc_V", "THD50_dur_pct", "trip"]:
            assert np.isclose(r["hil_"+metric], hil.loc[r.test_id, "hil_"+metric], atol=1e-9, rtol=0)
    hil_joint = hil.hil_power_retention_pct.sub(100).abs().le(1) & hil.hil_trip.eq(0)
    assert int(hil_joint.sum()) == 5
    costs = read("resources.csv").set_index("block")
    parts = ["mpcc_r_hls", "emi_feat_hls", "emi_detector_axi", "harmonic_estimator_axi", "axi_smc+gpio+timer+misc"]
    resource_cols = ["LUT", "FF", "RAMB36", "RAMB18", "DSP"]
    assert np.array_equal(costs.loc[parts, resource_cols].sum().values, costs.loc["total_design", resource_cols].values)
    timing = read("timing.csv")
    control = summaries.set_index("controller")
    h, r = control.loc["MPCC-H"], control.loc["MPCC-R"]
    validation = dict(source_files_verified=len(manifest), source_bytes=sum(e["bytes"] for e in manifest),
        matched_scorecards_verified=117, added_ablation_scorecards_verified=26,
        power_cases=13, power_subset_exclusions=sorted(POWER_EXCLUDED), thd_cases=11,
        thd_subset_exclusions=sorted(THD_EXCLUDED),
        bus_error_reduction_pct=100*(1-r.bus13_V/h.bus13_V),
        power_error_reduction_pct=100*(1-r.power13_pp/h.power13_pp),
        final_SIL_joint=[int(h.joint), int(r.joint)], IDS_any_hit_pct=100*102/104,
        full_HIL_pairs=7, full_HIL_joint=int(hil_joint.sum()),
        HIL_max_power_difference_pp=float(full.d_power_retention_pct.abs().max()),
        HIL_max_bus_difference_V=float(full.d_dVdc_V.abs().max()),
        HIL_max_THD_difference_pp=float(full.d_THD50_dur_pct.abs().max()),
        HIL_latch_pairs_equal=bool(full.d_trip.eq(0).all()),
        evidence_scope="Archived experiments; final SIL policy, historical HIL and independent local replay remain separate.")
    return membership, summaries, ablations, ids, hil, costs, timing, validation


def figures(destination):
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 8,
        "axes.spines.top": False, "axes.spines.right": False, "pdf.fonttype": 42,
        "svg.fonttype": "none", "axes.labelsize": 8, "legend.fontsize": 7})
    sweep = read("sweep_metrics.csv")
    fig, axes = plt.subplots(2, 3, figsize=(7.2, 4.1), constrained_layout=True)
    for col, (channel, prefix, name) in enumerate([("Vdc", "vdc", "DC-link bias"), ("Vac", "vac", "Grid-voltage bias"), ("Vbat", "vbat", "Battery-voltage bias")]):
        for row, (suffix, metric, ylabel) in enumerate([("thd", "THD50_display_pct", "THD50 (%)"), ("bus", "Vdc_dur_V", "True mean bus (V)")]):
            ax = axes[row, col]
            q = sweep[sweep.panel.eq(f"{'abcdef'[row*3+col]}_{prefix}_{suffix}")]
            # Panel IDs follow a,b,c for THD and d,e,f for voltage.
            assert len(q) > 0 and q.channel.eq(channel).all()
            for key in ["PR", "D", "H", "R"]:
                d = q[q.controller.eq(key)].sort_values("amp")
                assert len(d) > 0 and not d.amp.duplicated().any()
                ax.plot(d.amp, d[metric], marker="o", ms=3, lw=1, color=COLORS[key], label="PR" if key == "PR" else "MPCC-"+key)
            if row == 1: ax.axhline(400, color="#aaaaaa", ls=":", lw=.7)
            if row == 0 and col == 0: ax.set_yscale("log")
            ax.set_title(f"({'abcdef'[row*3+col]}) {name}", loc="left", fontsize=8)
            ax.set_xlabel("Injected bias (V)"); ax.set_ylabel(ylabel); ax.grid(alpha=.15)
    axes[0, 1].legend(loc="upper left", ncol=2, frameon=False)
    fig.savefig(destination / "attack_sweeps.pdf", metadata=PDF_METADATA); plt.close(fig)
    channels = read("ids_channels.csv")
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.7), constrained_layout=True)
    labels = ["Vdc", "Vac", "Iac", "Vbat", "Ibat"]
    for cohort, color, offset in [("phase1", "#2563a6", -.12), ("random20", "#22805e", .12)]:
        q = channels[channels.test_set.eq(cohort)].set_index("channel").loc[labels]
        for metric, marker, shift in [("precision", "o", -.04), ("recall", "^", .04)]:
            axes[0].scatter(q[metric], np.arange(5)+offset+shift, marker=marker, color=color, s=23,
                label=("Benchmark" if cohort == "phase1" else "Random")+" "+metric)
        d = read("ids_benchmark.csv" if cohort == "phase1" else "ids_random.csv")
        attacked = d[d.attacked.eq(1)]; latency = attacked.lat_ms.dropna().sort_values().values
        axes[1].step(np.r_[0, latency, 130], np.r_[0, np.arange(1, len(latency)+1)/len(attacked)*100, len(latency)/len(attacked)*100],
            where="post", color=color, label=f"{'Benchmark' if cohort == 'phase1' else 'Random'} (n={len(attacked)})")
    axes[0].set_yticks(np.arange(5), labels); axes[0].invert_yaxis(); axes[0].set_xlim(0, 105)
    axes[0].set_xlabel("Attack-cycle precision / recall (%)"); axes[0].set_title("(a) Channel attribution", loc="left")
    axes[0].legend(loc="lower left", fontsize=6, frameon=False)
    axes[1].set_xlabel("First detection after onset (ms)"); axes[1].set_ylabel("Detected attacked runs (%)")
    axes[1].set_xlim(0,130); axes[1].set_ylim(0,105); axes[1].set_title("(b) Coverage and observation delay",loc="left")
    axes[1].legend(loc="lower right",frameon=False)
    for ax in axes: ax.grid(alpha=.15)
    fig.savefig(destination / "ids_evaluation.pdf", metadata=PDF_METADATA); plt.close(fig)
    # Show per-case operating points; the power panel includes both uncompensated current biases.
    matched = read("matched_case_metrics.csv")
    cases = read("attack_membership.csv").query("cohort == 'main13'")["case"].tolist()
    fig, axes = plt.subplots(2,1,figsize=(7.2,4),sharex=True,constrained_layout=True)
    x = np.arange(13)
    for name, color, offset in [("MPCC-H", COLORS["H"], -.18), ("MPCC-R", COLORS["R"], .18)]:
        q = matched[matched.controller.eq(name)].set_index("test_id").loc[cases]
        axes[0].bar(x+offset,q.power_retention_pct,width=.35,color=color,label=name)
        axes[1].bar(x+offset,q.bus_deviation_V,width=.35,color=color)
        for i, (_,r) in enumerate(q.iterrows()):
            if r.latch_code != 0: axes[0].plot(i+offset,r.power_retention_pct+4,"x",color="#ad3434",ms=5)
    axes[0].axhline(100,color="#999999",lw=.7,ls=":"); axes[0].set_ylabel("Charging power retained (%)")
    axes[0].legend(loc="upper left",ncol=2,frameon=False); axes[0].set_ylim(0,140)
    axes[0].set_title("(a) Power recovery; crosses mark recorded latches",loc="left")
    axes[1].axhline(0,color="#999999",lw=.7); axes[1].set_ylabel("True mean bus deviation (V)")
    axes[1].set_title("(b) Regulation of the physical operating point",loc="left")
    axes[1].set_xticks(x,[c.replace("E-","") for c in cases],rotation=45,ha="right")
    fig.savefig(destination / "resilience_cases.pdf", metadata=PDF_METADATA); plt.close(fig)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manuscript", type=Path, help="Write LaTeX tables and vector figures into this manuscript repository")
    args = parser.parse_args()
    membership, summary, ablations, ids, hil, costs, timing, audit = calculate()
    derived = HERE / "derived"; derived.mkdir(exist_ok=True)
    for name, frame in [("controllers",summary),("ablations",ablations),("ids",ids)]:
        frame.to_csv(derived / f"{name}.csv",index=False,float_format="%.10g")
    (derived / "validation.json").write_text(json.dumps(audit,indent=2)+"\n")
    if args.manuscript:
        root = args.manuscript.resolve(); out = root / "tables"; out.mkdir(exist_ok=True)
        figs = root / "figs" / "results"; figs.mkdir(parents=True,exist_ok=True)
        cases = membership[membership.cohort.eq("main13")]
        attack_labels = {
            "E-DC-01b":r"$V_{dc}$ step $+50$ V", "E-DC-01c":r"$V_{dc}$ step $+100$ V",
            "E-DC-02b":r"$V_{dc}$ ramp $-100$ V, $-1000$ V/s",
            "E-AC-01a":r"$V_{ac}$ step $+17$ V", "E-AC-01b":r"$V_{ac}$ step $+34$ V",
            "E-AC-02b":r"$I_{ac}$ step $+5$ A", "E-AC-02s":r"$I_{ac}$ 50 Hz sine, 10 A, $90^\circ$",
            "E-AC-02h":r"$I_{ac}$ Hall: 4 A + 10 A at 100 Hz",
            "E-MUL-01":r"$V_{dc}+50$ V and $I_{ac}+5$ A",
            "E-BAT-01b":r"$I_{bat}$ step $+5$ A", "E-BAT-01n":r"$I_{bat}$ step $-5$ A",
            "E-BAT-02b":r"$V_{bat}$ step $+10$ V", "E-BAT-02c":r"$V_{bat}$ step $+20$ V"}
        table(out/"attack_cases.tex","Common sensor-attack benchmark and complete-loop hardware coverage.","tab:attack-cases","llc",
            ["Case","Injected measurement error","Full HIL"],
            [(r.case,attack_labels[r.case],"Yes" if r.complete_hil else "---") for r in cases.itertuples()],
            r"All 13 cases belong to the final SIL development benchmark. The seven HIL cases test the earlier response configuration. Onset is 0.70 s and duration is 0.30 s. Error amplitudes describe controller-visible samples, rather than RF field strength.")
        table(out/"controller_comparison.tex","Controller performance under 13 common attacks.","tab:controller-comparison","lrrrrrr",
            ["Controller",r"$f_c$ (kHz)",r"THD pre / attack (\%)",r"$|\Delta P|$ (pp)",r"$|\Delta V|$ (V)","Latch","Joint"],
            [(r.controller,r.control_kHz,f"{r.thd_pre_pct:.2f} / {r.thd_attack_pct:.2f}",f"{r.power13_pp:.2f}",f"{r.bus13_V:.2f}",r.latches,r.joint) for r in summary.itertuples()],
            r"Power and bus entries are mean absolute errors over all 13 cases; latch and joint entries are counts out of 13. Joint success requires power retention within 1 pp of 100\% and no latch. THD means use the same 11 active-charging cases for every controller, excluding DC-01c and BAT-02c. PR and MPCC-P update at 100 kHz and serve as contextual references. MPCC-H/R use the final v6 scorecards.")
        table(out/"detector_evaluation.tex","IDS coverage on archived software trajectories.","tab:detector-evaluation","lrr",
            ["Metric","Benchmark","Random"],
            [("Attacked / benign runs",*(f"{r.attacked} / {r.benign}" for r in ids.itertuples())),
             ("Any attacked-channel hit",*(f"{r.any_hit}/{r.attacked} ({100*r.any_hit/r.attacked:.1f}"+r"\%)" for r in ids.itertuples())),
             ("Exact attacked-channel set",*(f"{r.exact}/{r.attacked}" for r in ids.itertuples())),
             ("Detected by 40 ms",*(f"{r.detected_by_40ms}/{r.attacked}" for r in ids.itertuples())),
             ("Median / maximum hit latency (ms)",*(f"{r.median_ms:.1f} / {r.max_ms:.1f}" for r in ids.itertuples())),
             ("Pre-attack flagged cycles",f"{ids.iloc[0].pre_flags}/520",f"{ids.iloc[1].pre_flags}/142"),
             ("Benign flagged cycles","---",f"{ids.iloc[1].benign_flags}/106"),
             ("Post-attack flagged cycles",*(str(r.post_flags) for r in ids.itertuples()))],
            r"The benchmark repeats 13 attacks under eight unprotected controllers. Exact-set agreement uses the union of flags during attack-overlapping windows; hit latency excludes misses, while the coverage denominator retains them. Persistence, hysteresis and priority are applied. Original cycle denominators are preserved from the archived protocol; post-attack denominators are unavailable. These are neither HIL detection rates nor same-run detector metrics for final MPCC-R.")
        table(out/"resilience_ablations.tex","Detection, correction timing and handover ablations.","tab:resilience-ablations","lrrrr",
            ["Configuration",r"$|\Delta P|_{11}$ (pp)",r"$E_{def}$ (kJ)","Latch/13","Joint/13"],
            [(r.configuration,"<0.001" if r.power11_pp<.001 else f"{r.power11_pp:.2f}",f"{r.energy_kJ:.2f}",r.latches,r.joint) for r in ablations.itertuples()],
            r"The power-11 subset excludes the two battery-current biases, unlike the THD-11 subset in Table~\ref{tab:controller-comparison}. Energy deficit sums the complete 0.30 s attack interval across all 13 cases. The two safeguards are the 55 A reference limit and corrected predictor input. Oracle flags supply the true attacked-channel set.")
        table(out/"hil_outcomes.tex","Electrical outcomes in seven complete MATLAB--PL feedback experiments.","tab:hil-outcomes","lrrrr",
            ["Attack",r"Power (\%)",r"$\Delta V_{dc}$ (V)",r"THD50 (\%)","Latch"],
            [(attack_labels[c],f"{r.hil_power_retention_pct:.3f}",f"{r.hil_dVdc_V:+.3f}",f"{r.hil_THD50_dur_pct:.3f}","OV" if r.hil_trip else "---") for c,r in hil.iterrows()],
            r"Power retention, true-bus deviation from 400 V and THD use the late attack window. All hardware component paths participate. OV denotes a latched over-voltage event. These paired HIL tests precede the final SIL reference-limit and predictor-feedback revision.")
        parts=[("mpcc_r_hls","Duty controller"),("emi_feat_hls","Window processing"),("emi_detector_axi","Neural detector"),("harmonic_estimator_axi","Harmonic estimator"),("axi_smc+gpio+timer+misc","Interfaces and timing"),("+ detection (emi_feat + detector)","Detection subtotal"),("total_design","Full design")]
        table(out/"hardware_resources.tex","Implemented PL resources on the ZCU104.","tab:hardware-resources","lrrrr",
            ["Block","LUT","FF","RAMB36/18","DSP"],
            [(label,f"{int(costs.loc[key,'LUT']):,}",f"{int(costs.loc[key,'FF']):,}",f"{int(costs.loc[key,'RAMB36'])}/{int(costs.loc[key,'RAMB18'])}",int(costs.loc[key,'DSP'])) for key,label in parts],
            r"Counts include implemented wrappers and interfaces. Detection subtotal combines window processing and neural detection; harmonic estimation is separate. Full-design occupancy is 34.8\% of LUTs and 46.5\% of DSPs. Historical HLS estimates are not substituted for implemented resources.")
        def stat(task, quantity):
            q=timing[timing.task.eq(task)&timing.quantity.eq(quantity)]; assert len(q)==1
            return q.iloc[0]
        rows=[]
        for task,label,period in [("mpcc","Control",50),("estimator","Harmonic",250),("detector","Detection",20000)]:
            s=stat(task,"service");r=stat(task,"end_to_end");late=stat(task,"late")
            assert s.n==r.n
            rows.append((label,f"{period:,}",f"{s.median_us:.2f}/{s.p99_us:.2f}",f"{r.p99_us:.2f}/{r.max_us:.2f}",f"{int(late.n)}/{int(s.n)}"))
        table(out/"hardware_timing.tex","Concurrent local board replay over 20 s.","tab:hardware-timing","lrrrr",
            ["Task",r"Period ($\mu$s)","Service med/p99","Response p99/max","Late / releases"],rows,
            r"All times are in $\mu$s. Service includes board transfers, driver and PL invocation; response also includes release-to-start waiting. Late means response exceeds the task period. These original summaries exclude MATLAB--board network round trips and do not establish hard real-time operation; no new board replay was performed for this compilation.")
        figures(figs)
    print(json.dumps(audit,indent=2))


if __name__ == "__main__":
    main()
